/**
 * CLC Kernel — Non-Destructive Harness Updater
 * Safely updates core guard tools, skills, playbooks, and IDE symlinks in an existing
 * project while guaranteeing 100% preservation of:
 * - Local specifications (sdds/)
 * - Project guards (tools/guards/, and guard files in tools/ the kernel does not ship)
 * - Project configuration and custom thresholds (.clckernel.yaml, or an older config name)
 * - Application source code and domain models
 */

const fs = require('fs');
const path = require('path');
const { autoDetectStack } = require('./detector');
const { generateHarness, manifestGuardNames } = require('./generator');
const { createIO, runWithIO, currentIO, sha256, NEW_SUFFIX } = require('./io');
const { CONFIG_NAMES, readProjectConfig, globMatcher } = require('./config');

// Artifacts written by releases that still used the old project name.
const SKILLS_REL = path.join('.agents', 'skills');
const LEGACY_SKILL = 'clc_forge_cli';
const CURRENT_SKILL = 'clckernel_cli';
const LEGACY_CURSOR_RULE = '.cursor/rules/clc_forge_context.mdc';
const LEGACY_RESOLVED_JSON = '.clc-forge.resolved.json';
const BUNDLED_SKILL_DIR = path.join(__dirname, '..', SKILLS_REL, CURRENT_SKILL);

// Guard file names the audit orchestrators discover at the top of tools/
// (sdds/unified-discovery): check_*, scan_*, verify_* or *_guard, .js or .py.
const GUARD_FILE_RE = /^tools\/(?:(?:check|scan|verify)_[^/]*|[^/]*_guard)\.(?:js|py)$/;

/**
 * Read every regular file under `dir` into a map of relative path -> bytes.
 * Anything that is not a directory or a regular file (e.g. a symlink) is
 * recorded under `others`, since it cannot have come from us.
 */
function snapshotFiles(dir) {
  const files = new Map();
  const others = [];
  if (!fs.existsSync(dir)) return { files, others };
  const walk = (current) => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const full = path.join(current, entry.name);
      const rel = path.relative(dir, full).split(path.sep).join('/');
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile()) files.set(rel, fs.readFileSync(full));
      else others.push(rel);
    }
  };
  walk(dir);
  return { files, others };
}

/**
 * Why the legacy skill dir is not provably ours, or null when it is: every
 * file must be byte-identical to the same file in the bundled skill or in the
 * project's clckernel_cli as it was before this update (older releases wrote
 * both directories with the same bytes).
 */
function legacySkillMismatch(legacyDir, references) {
  const { files, others } = snapshotFiles(legacyDir);
  if (others.length) return `not a regular file: ${others[0]}`;
  for (const [rel, bytes] of files) {
    const known = references.some((ref) => ref.has(rel) && ref.get(rel).equals(bytes));
    if (!known) {
      const listed = references.some((ref) => ref.has(rel));
      return listed ? `modified file: ${rel}` : `unknown file: ${rel}`;
    }
  }
  return null;
}

/**
 * Remove artifacts left by releases that used the old name, only when they
 * are provably generated by us. Anything else is kept and reported.
 * @param {string} dir - Project root
 * @param {Map<string, Buffer>} previousSkill - clckernel_cli files before this update
 * @returns {{ removed: string[], kept: {path: string, reason: string}[] }}
 */
function cleanupLegacyArtifacts(dir, previousSkill) {
  const removed = [];
  const kept = [];
  const lstat = (p) => {
    try { return fs.lstatSync(p); } catch { return null; }
  };

  const skillDir = path.join(dir, SKILLS_REL, LEGACY_SKILL);
  const skillLabel = `.agents/skills/${LEGACY_SKILL}/`;
  const skillStat = lstat(skillDir);
  if (skillStat) {
    if (!skillStat.isDirectory()) {
      kept.push({ path: skillLabel, reason: 'not a directory' });
    } else {
      const bundled = snapshotFiles(BUNDLED_SKILL_DIR).files;
      const mismatch = legacySkillMismatch(skillDir, [bundled, previousSkill]);
      if (mismatch) {
        kept.push({ path: skillLabel, reason: mismatch });
      } else if (currentIO(dir).remove(skillDir) === 'excluded') {
        kept.push({ path: skillLabel, reason: 'excluded by config (update.exclude)' });
      } else {
        removed.push(skillLabel);
      }
    }
  }

  const rulePath = path.join(dir, LEGACY_CURSOR_RULE);
  const ruleStat = lstat(rulePath);
  if (ruleStat) {
    const pointsToAgents =
      ruleStat.isSymbolicLink() &&
      path.resolve(path.dirname(rulePath), fs.readlinkSync(rulePath)) === path.join(dir, 'AGENTS.md');
    if (pointsToAgents && currentIO(dir).remove(rulePath) === 'excluded') {
      kept.push({ path: LEGACY_CURSOR_RULE, reason: 'excluded by config (update.exclude)' });
    } else if (pointsToAgents) {
      removed.push(LEGACY_CURSOR_RULE);
    } else {
      kept.push({
        path: LEGACY_CURSOR_RULE,
        reason: ruleStat.isSymbolicLink() ? 'symlink does not point to AGENTS.md' : 'not a symlink to AGENTS.md',
      });
    }
  }

  const jsonPath = path.join(dir, LEGACY_RESOLVED_JSON);
  const jsonStat = lstat(jsonPath);
  if (jsonStat) {
    if (jsonStat.isFile() && currentIO(dir).remove(jsonPath) === 'excluded') {
      kept.push({ path: LEGACY_RESOLVED_JSON, reason: 'excluded by config (update.exclude)' });
    } else if (jsonStat.isFile()) {
      removed.push(LEGACY_RESOLVED_JSON);
    } else {
      kept.push({ path: LEGACY_RESOLVED_JSON, reason: 'not a regular file' });
    }
  }

  return { removed, kept };
}

/**
 * Kernel guards this update retired (sdds/unified-discovery, decision 6): a
 * guard file in tools/ that the kernel wrote before — listed in the prior
 * registry, or byte-identical to a version it published — and that this run
 * did not write because the current manifest no longer ships it. Nothing is
 * moved or deleted: the file stays where it is (siblings it requires keep
 * resolving), leaves the registry (rebuilt from what this run wrote), and the
 * audit orchestrators keep running it as a project guard.
 * @param {object} io - The update's io session (after generateHarness)
 * @param {string} dir - Project root
 * @param {object} knownHashes - { path: [sha256] } of published versions
 * @returns {string[]} Root-relative paths, sorted
 */
function retiredKernelGuards(io, dir, knownHashes) {
  const plan = io.plan();
  const decided = new Set([
    ...io.managedEntries().map((entry) => entry.path),
    ...plan.protected.map((entry) => entry.path),
    ...plan.excluded,
  ]);
  const candidates = new Set([...io.registry.paths, ...Object.keys(knownHashes)]);
  const retired = [];
  for (const rel of candidates) {
    if (!GUARD_FILE_RE.test(rel) || decided.has(rel)) continue;
    const bytes = io.read(path.join(dir, rel));
    if (!bytes) continue;
    const ours = io.registry.paths.includes(rel) || (knownHashes[rel] || []).includes(sha256(bytes));
    if (ours) retired.push(rel);
  }
  return retired.sort();
}

/**
 * Checks --add-guards against the stack's manifest.
 * @param {string[]|'all'|undefined} requested - Guard names, or 'all'
 * @param {string[]} offered - Guard names of the stack's manifest
 * @returns {string[]|'all'} The guards to add
 * @throws {Error} When a name is not a guard of this stack
 */
function validateAddGuards(requested, offered) {
  if (requested === undefined || requested === null) return [];
  if (requested === 'all') return 'all';
  const unknown = requested.filter((name) => !offered.includes(name));
  if (unknown.length > 0) {
    throw new Error(
      `Unknown guard(s) for --add-guards: ${unknown.join(', ')}. ` +
        `This stack offers: ${offered.join(', ') || '(none)'}. Nothing was written.`
    );
  }
  return [...requested];
}

/**
 * Refreshes the harness of an installed project. It updates what the project
 * has and never adds guards or mirrors it does not have
 * (sdds/update-no-additions); options.addGuards opts guards in.
 * @param {string} [targetDir] - Project root
 * @param {{ dryRun?: boolean, addGuards?: string[]|'all', knownHashes?: object }} [options]
 */
function updateHarness(targetDir = process.cwd(), options = {}) {
  const resolvedDir = path.resolve(targetDir);

  if (!fs.existsSync(resolvedDir)) {
    throw new Error(`Target directory "${resolvedDir}" does not exist.`);
  }

  // The project config is read before anything is written: an invalid one
  // throws its ConfigError and the update writes nothing (sdds/config-foundation).
  const projectConfig = readProjectConfig(resolvedDir);

  // 1. Detect Stack
  const detected = autoDetectStack(resolvedDir);

  // --add-guards is checked before anything is written: an unknown name
  // fails the whole update (sdds/update-no-additions, decision 1).
  const addGuards = validateAddGuards(options.addGuards, manifestGuardNames(resolvedDir, detected));

  // 2. Identify existing preserved assets
  const preserved = {
    sdds: fs.existsSync(path.join(resolvedDir, 'sdds')),
    customGuards: fs.existsSync(path.join(resolvedDir, 'tools', 'guards')),
    configYaml: CONFIG_NAMES.some((name) => fs.existsSync(path.join(resolvedDir, name))),
  };

  // 3. Run harness generation (refreshes tools, hooks, skills, and symlinks)
  // inside one io session (sdds/safe-update): every write follows the
  // ownership rule, and a dry run only records the plan.
  const { loadKnownHashes } = require('./io');
  const knownHashes = options.knownHashes || loadKnownHashes();
  const io = createIO({
    root: resolvedDir,
    dryRun: !!options.dryRun,
    knownHashes,
    mode: 'update',
    exclude: globMatcher(projectConfig.config.update.exclude),
  });
  const { retiredGuards, legacyCleanup } = runWithIO(io, () => {
    // Snapshot the installed skill first: the legacy copy is compared against it.
    const previousSkill = snapshotFiles(path.join(resolvedDir, SKILLS_REL, CURRENT_SKILL)).files;
    generateHarness(resolvedDir, detected, { addGuards, projectConfig });
    const retired = retiredKernelGuards(io, resolvedDir, knownHashes);
    const cleanup = cleanupLegacyArtifacts(resolvedDir, previousSkill);
    const { ensureGitignoreEntries } = require('./gitignore');
    ensureGitignoreEntries(resolvedDir);
    injectUpdateRow(io, resolvedDir);
    return { retiredGuards: retired, legacyCleanup: cleanup };
  });

  return {
    success: true,
    targetDir: resolvedDir,
    dryRun: io.dryRun,
    preserved,
    configWarnings: projectConfig.warnings,
    legacyCleanup,
    retiredGuards,
    plan: io.plan(),
    refreshed: {
      tools: true,
      skills: true,
      symlinks: true,
      hooks: true,
    },
  };
}

/**
 * Ensures AGENTS.md documents the update command in its command table.
 * Non-destructive: only inject into a file that already carries the CLC
 * Kernel command table, and only when the row is missing (idempotent).
 * A project-customized AGENTS.md without that structure is left untouched.
 */
function injectUpdateRow(io, resolvedDir) {
  const agentsPath = path.join(resolvedDir, 'AGENTS.md');
  const current = io.read(agentsPath);
  if (!current) return;
  let agentsContent = current.toString('utf-8');
  if (agentsContent.includes('clckernel update')) return;
  if (agentsContent.includes('| `clckernel start`')) {
    agentsContent = agentsContent.replace(
      '| `clckernel start`',
      '| `clckernel update` | Maintenance | Non-destructive update: run `npx clckernel update [dir]` (`--dry-run` previews, `--add-guards <a,b\\|all>` adds guards); refreshes kernel tools, hook, playbooks & symlinks (preserves SDDs, project guards, edited files & `.clckernel.yaml`). |\n| `clckernel start`'
    );
    io.writeFile(agentsPath, agentsContent);
  } else if (agentsContent.includes('## 3. Universal Command Interface')) {
    agentsContent += '\n| `clckernel update` | Maintenance | Non-destructive update: run `npx clckernel update [dir]` (`--dry-run` previews, `--add-guards <a,b\\|all>` adds guards); refreshes kernel tools, hook, playbooks & symlinks (preserves SDDs, project guards, edited files & `.clckernel.yaml`). |\n';
    io.writeFile(agentsPath, agentsContent);
  }
}

async function runUpdate(targetDir = process.cwd(), options = {}) {
  const { colors, printBanner, printPlan } = require('./ui');
  const dryRun = !!options.dryRun;
  printBanner();

  console.log(`\n${colors.cyan}🔄 Actualizando CLC Kernel en:${colors.reset} ${targetDir}${dryRun ? ' (dry run)' : ''}\n`);

  try {
    const result = updateHarness(targetDir, { dryRun, addGuards: options.addGuards });

    for (const warning of result.configWarnings) {
      console.log(`${colors.amber}⚠ ${warning}${colors.reset}`);
    }
    for (const retiredPath of result.retiredGuards) {
      console.log(`${colors.amber}⚠ ${retiredPath}: retired kernel guard kept as project guard (the kernel no longer ships it; the hook and the audit still run it)${colors.reset}`);
    }
    for (const { path: keptPath, reason } of result.legacyCleanup.kept) {
      console.log(`${colors.amber}⚠ Kept legacy artifact ${keptPath} (${reason}); review and remove it manually${colors.reset}`);
    }
    console.log('');
    printPlan(result.plan, { dryRun });
    console.log(`\n${colors.bold}🔒 ACTIVOS PRESERVADOS AL 100%:${colors.reset}`);
    console.log(`   • ${colors.emerald}sdds/${colors.reset} (Especificaciones locales intactas)`);
    console.log(`   • ${colors.emerald}tools/guards/${colors.reset} (Reglas y salvaguardas personalizadas intactas)`);
    console.log(`   • ${colors.emerald}.clckernel.yaml${colors.reset} (Configuraciones de equipo intactas)\n`);
    if (dryRun) {
      console.log(`${colors.cyan}Dry run complete. Run without --dry-run to apply this plan.${colors.reset}\n`);
    } else if (result.plan.protected.length > 0) {
      console.log(`${colors.amber}✨ Proyecto actualizado, con ${result.plan.protected.length} archivo(s) protegido(s) para revisar (*${NEW_SUFFIX}).${colors.reset}\n`);
    } else {
      console.log(`${colors.emerald}✨ ¡Proyecto actualizado con éxito a la última versión de CLC Kernel!${colors.reset}\n`);
    }
    return result;
  } catch (err) {
    console.error(`\n❌ Error actualizando el arnés: ${err.message}`);
    process.exit(1);
  }
}

module.exports = { updateHarness, runUpdate };
